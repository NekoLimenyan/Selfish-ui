$utf8NoBom = New-Object System.Text.UTF8Encoding($false)
$root = $PSScriptRoot

# 1. Збірка CSS
$cssOrder = @("base.css", "fixes.css", "settings.css", "fullscreen.css")
$cssOut = "/* Generated by build.ps1 - DO NOT EDIT DIRECTLY */`n"
foreach ($file in $cssOrder) {
    $path = Join-Path $root "styles\$file"
    $cssOut += "`n/* === $file === */`n" + [System.IO.File]::ReadAllText($path, [System.Text.Encoding]::UTF8) + "`n"
}
[System.IO.File]::WriteAllText((Join-Path $root "user.css"), $cssOut, $utf8NoBom)

# 2. Збірка JS
$jsOrder = @("db.js", "engine.js", "settings.js", "fullscreen.js", "main.js")
$jsOut = "/* Generated by build.ps1 - DO NOT EDIT DIRECTLY */`n(function () {`nconst Selfish = {};`n"
foreach ($file in $jsOrder) {
    $path = Join-Path $root "src\$file"
    $jsOut += "`n// === $file ===`n" + [System.IO.File]::ReadAllText($path, [System.Text.Encoding]::UTF8) + "`n"
}
$jsOut += "`n})();`n"
[System.IO.File]::WriteAllText((Join-Path $root "theme.js"), $jsOut, $utf8NoBom)

Write-Host "[Selfish UI] Build complete! Applying theme..." -ForegroundColor Magenta
